package setup

import (
	"bytes"
	"encoding/xml"
)

// LaunchdDir is where macOS system-wide daemons are defined.
const LaunchdDir = "/Library/LaunchDaemons"

// labelBase is the launchd label of the default instance (reverse-DNS, as launchd expects).
const labelBase = "io.github.jecklgamis.microtunnel"

// Label is the launchd label of the instance called name: the plain label for the
// default instance and "<label>.<name>" for a named one (the macOS counterpart of
// the systemd units microtunnel and microtunnel@<name>).
func Label(name string) string {
	if name == "" || name == DefaultName {
		return labelBase
	}
	return labelBase + "." + name
}

// PlistPath is where the launchd job for the instance lives.
func PlistPath(name string) string { return LaunchdDir + "/" + Label(name) + ".plist" }

// LogFile is where the launchd job writes the daemon's output.
func LogFile(name string) string {
	if name == "" || name == DefaultName {
		return "/var/log/microtunnel.log"
	}
	return "/var/log/microtunnel-" + name + ".log"
}

// LaunchdPlist renders the launchd job that runs `binary -c configFile` as root.
// KeepAlive is tied to the config file: launchd starts the daemon only while the
// config exists (so nothing crash-loops before `init` has run) and restarts it if
// it exits. The packaged plist for the default instance is generated by this
// same function (see packaging/macos).
func LaunchdPlist(name, binary, configFile string) string {
	var b bytes.Buffer
	esc := func(s string) string {
		var e bytes.Buffer
		_ = xml.EscapeText(&e, []byte(s))
		return e.String()
	}
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>Label</key>
	<string>` + esc(Label(name)) + `</string>
	<key>ProgramArguments</key>
	<array>
		<string>` + esc(binary) + `</string>
		<string>-c</string>
		<string>` + esc(configFile) + `</string>
	</array>
	<key>RunAtLoad</key>
	<true/>
	<key>KeepAlive</key>
	<dict>
		<key>PathState</key>
		<dict>
			<key>` + esc(configFile) + `</key>
			<true/>
		</dict>
	</dict>
	<key>ThrottleInterval</key>
	<integer>5</integer>
	<key>StandardOutPath</key>
	<string>` + esc(LogFile(name)) + `</string>
	<key>StandardErrorPath</key>
	<string>` + esc(LogFile(name)) + `</string>
</dict>
</plist>
`)
	return b.String()
}
